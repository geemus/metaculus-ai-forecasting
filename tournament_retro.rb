#!/usr/bin/env ruby
# frozen_string_literal: true

require_relative 'lib/script_helpers'

tournament_id = ARGV[0] || raise('tournament id argument is required')

questions = Metaculus.list_resolved_tournament_questions(tournament_id)

puts "NOTE: doesn't paginate, so will miss questions if there are more than 100"

# Extract full XML elements including attributes (for self-closing-like
# elements like <forecaster provider="..." ...>content</forecaster>)
def extract_full_elements(text, tag)
  text.scan(%r{<#{tag}[^>]*>[\s\S]*?</#{tag}>}).map(&:strip)
end

data = []
missing_comments = 0
questions.reject! { |q| q.spot_peer_score.nil? }
questions.sort_by!(&:spot_peer_score)
questions.reverse!
questions.each_with_index do |q, _i|
  comment_text = q.my_comment
  missing_comments += 1 if comment_text.start_with?('Comments unavailable')

  # Extract structured sub-tags from pipeline comments
  research_summary = extract_xml(comment_text, 'research_summary').first
  consensus_analysis = extract_xml(comment_text, 'consensus_analysis').first
  forecasters = extract_full_elements(comment_text, 'forecaster')
  final_forecast = extract_xml(comment_text, 'probability', 'percentiles', 'probabilities').first

  # Build structured comment section
  comment_tags = []
  comment_tags << "<research_summary>#{research_summary}</research_summary>" if research_summary
  forecasters.each { |f| comment_tags << "  #{f}" }
  comment_tags << "<consensus_analysis>#{consensus_analysis}</consensus_analysis>" if consensus_analysis
  comment_tags << "<final_forecast>#{final_forecast}</final_forecast>" if final_forecast
  # Fallback: include raw comment for non-pipeline questions or when no tags match
  comment_tags << "<raw_comment>#{comment_text}</raw_comment>" if comment_tags.empty? && !comment_text.empty?

  data << <<~QUESTION
    <forecast>
      <id>#{q.post_id}</id>
      <title>#{q.title}</title>
      <type>#{q.type}</type>
      <spot_peer_score>#{q.spot_peer_score.round}</spot_peer_score>
      <resolution>#{q.resolution}</resolution>
      <my_prediction>#{q.my_prediction}</my_prediction>
      <error>#{q.error_summary}</error>
      <comment>
    #{comment_tags.join("\n")}
      </comment>
    </forecast>
  QUESTION
end

Formatador.display "\n[bold][green]# Retro: Reviewing Scores(#{tournament_id})…[/] "

forecaster_count = Provider::FORECASTERS.length
forecaster_names = Provider::FORECASTERS.join(', ')
comment_coverage = if data.empty? || missing_comments * 2 <= data.length
                     ''
                   else
                     <<~COVERAGE
                       ## Comment Data Coverage

                       Structured comment data is missing for #{missing_comments} of #{data.length} questions. With that little forecaster-level data, skip the provider, Delphi-revision, meta-forecaster, and research-quality analyses entirely and say so in one line — do not infer them from outcome patterns. Spend the analysis on the outcome data instead.
                     COVERAGE
                   end
warn "WARNING: comment data missing for #{missing_comments}/#{data.length} questions" if missing_comments.positive?

provider = :anthropic
llm = Provider.new(provider, model: 'anthropic/claude-opus-5.5', system: '', tools: [])

retro_prompt = <<~RETRO_PROMPT
  These forecasts were generated by an automated multi-stage forecasting pipeline: News → Research → #{forecaster_count} independent Forecasters → Delphi Revise (each sees peers' estimates) → Consensus.

  ## Comment Data Structure

  Pipeline-generated questions include structured XML in their comments:
  - `<research_summary>` — The research phase findings used by all forecasters
  - `<forecaster>` — Per-provider forecast with attributes:
    - `provider` — Model name (#{forecaster_names})
    - `value` — Final (post-revision) forecast value
    - `pre_revision` — Forecast value BEFORE the Delphi revise stage (enables measuring herding vs. refinement)
    - `confidence` — Self-assessed confidence rating
    - Content: Key argument summary
  - `<consensus_analysis>` — The meta-forecaster's synthesis reasoning
  - `<final_forecast>` — The submitted consensus forecast value
  - `<raw_comment>` — Fallback for questions without pipeline-structured comments

  Questions without pipeline comments use `<raw_comment>` only — analyze these using score/prediction patterns.

  ## Outcome Fields

  - `<my_prediction>` — the submitted forecast (binary: P(Yes); numeric/discrete: P50; multiple choice: all options)
  - `<error>` — computed from the outcome. Binary: which side of 50% the forecast fell relative to the resolution, the gap in points, and Brier score. Numeric/discrete: P10/P50/P90, the P50 error, and the forecast percentile at which the resolution landed — peer score depends on the density there, so a small P50 error can still score badly when the distribution is narrow. Multiple choice: probability and rank of the correct option, and Brier score.

  #{comment_coverage}
  ## Pipeline Prompts (verbatim)

  These are every prompt the pipeline sends, labelled by file or constant. They already carry many rules: check here before recommending anything, and quote from here when you do.

  #{pipeline_prompts_for_retro}
  ## Forecast Data

  <forecasts>
  #{data.join.strip}
  </forecasts>

  ## Analysis

  Review this data thoroughly to improve the pipeline:
    - identify commonalities among the lowest and highest scores
    - analyze error patterns: direction (over/under confident), magnitude, and question-type trends — including whether extreme probabilities (near 0% or 100%) are well calibrated
    - where structured comment data is available: evaluate forecaster-level performance by provider — do certain providers consistently outperform? Is the Delphi revision stage causing herding (convergence toward median without accuracy gain, visible in pre_revision vs. value) or productive refinement (movement toward resolution)?
    - evaluate whether the meta-forecaster identified the right divergences between forecasters, and whether the underlying forecaster reasoning revealed flawed assumptions, missing base rates, or confirmation bias
    - assess research quality by comparing `<research_summary>` content against question outcomes — are there recurring research gaps?
    - identify which question types the pipeline performs best/worst on and hypothesize why (prompt fit, inherent difficulty, research quality, aggregation dynamics)
    - for each error pattern, identify which pipeline stage is the most likely source: research gaps, forecaster prompt issues, revision dynamics, or consensus synthesis failures

  ## Recommendations

  A retro that only adds rules makes the prompts longer and more redundant each cycle, and a long list of changes drawn from one tournament mostly fits noise. Follow these rules:

  1. **Top changes (at most 3)**, ranked by expected score impact. A change may target any stage — research, forecaster, question-type, revision, or consensus prompts, or the aggregation code. For each:
     - Evidence: the question ids behind it and how many. Do not recommend a change supported by fewer than 3 questions; list such patterns under **Watch list** instead, one line each.
     - Existing coverage: quote the current prompt text that already addresses this pattern, or state that you checked the prompts above and none does. If an existing instruction covers the pattern but the forecasts show it failing, prefer rewording, strengthening, or replacing it over adding a new one.
     - Edit: the file or constant, the exact current text (or "new"), and the exact proposed text.
  2. **Remove or merge (required)**: instructions that duplicate each other, that the data gives no evidence are helping, or that the forecasts visibly ignore — proposed for deletion or merging, in the same current/proposed format. Aim for your edits, taken together, to shorten the prompts.
  3. **Watch list**: patterns seen in fewer than 3 questions, one line each with the question ids.
  4. **This retro prompt**: at most one change, under the same rules — quote the text it replaces, and prefer a removal or rewording to an addition.
RETRO_PROMPT

retro = llm.eval({ 'role': 'user', 'content': retro_prompt })
puts retro.content
